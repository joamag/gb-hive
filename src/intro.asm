; Hive Solutions intro (DMG and CGB).
;
; A bee (the Hive logo in miniature) flies around the screen, lands and
; grows into the logo, then a second bee writes "HIVE SOLUTIONS" and keeps
; orbiting the logo, passing behind it on the far side of the orbit.
;
; It runs in two modes, picked by the caller:
; - standalone (a = 0): never returns, START or A replays the intro
; - embedded (a = 1): returns after one orbit, or right away on START or A,
;   leaving a white screen for whatever comes next
;
; Efficiency notes:
; - the CPU sleeps in `halt` until VBlank, which is the only interrupt
; - each VBlank only pushes a prepared frame to the hardware: one OAM DMA,
;   a couple of registers and, when requested, a palette
; - all motion comes from tables generated by tools/gen.py, so the per
;   frame logic is a handful of table reads (no math at runtime)
; - the logo and the text live in the background map from the start and
;   are hidden by the palette, revealing them costs a single palette write
; - the text is uncovered by sliding the window layer (one register)

INCLUDE "hardware.inc"
INCLUDE "intro_assets.inc"

DEF STATE_FADE_IN  EQU 0
DEF STATE_FLY      EQU 1
DEF STATE_ZOOM     EQU 2
DEF STATE_REVEAL   EQU 3
DEF STATE_WRITE    EQU 4
DEF STATE_FADE_OUT EQU 5

DEF NOTE_C6 EQU 1923 ; 2048 - 131072 / 1046.5 Hz
DEF NOTE_G6 EQU 1964 ; 2048 - 131072 / 1568.0 Hz

DEF LCDC_DEFAULT EQU LCDCF_ON | LCDCF_WIN9C00 | LCDCF_WINON | LCDCF_BG8000 \
    | LCDCF_OBJ16 | LCDCF_OBJON | LCDCF_BGON

SECTION "Intro", ROM0

; in: a = 0 standalone (never returns), 1 embedded (returns when done)
Intro::
    ldh [hIntroMode], a
    xor a
    ldh [hIntroDone], a
    call LcdOff

    ld hl, TileData
    ld de, _VRAM
    ld bc, TileDataEnd - TileData
    call Copy

    ; both tile maps cleared to the background tile
    ld hl, _SCRN0
    ld bc, $0800
    ld d, 0
    call Fill

    ; logo and text patches (hidden by the palette for now)
    ld hl, MapPatches
.patch:
    ld a, [hl+]
    ld e, a
    ld a, [hl+]
    ld d, a
    or e
    jr z, .patchesDone
    ld c, [hl]
    inc hl
.patchByte:
    ld a, [hl+]
    ld [de], a
    inc de
    dec c
    jr nz, .patchByte
    jr .patch
.patchesDone:

    ld hl, wShadowOAM
    ld bc, OAM_COUNT * 4
    ld d, 0
    call Fill

    ldh a, [hIsCGB]
    and a
    jr z, .dmgPalettes

    ; CGB: one palette per gradient band, set per map row (VRAM bank 1)
    ld a, 1
    ldh [rVBK], a
    ld hl, _SCRN0
    ld de, AttrRows
    ld b, 64 ; 32 rows of the BG map followed by 32 of the window map
.attrRow:
    ld a, [de]
    inc de
    ld c, 32
.attrCol:
    ld [hl+], a
    dec c
    jr nz, .attrCol
    dec b
    jr nz, .attrRow
    xor a
    ldh [rVBK], a

    ld a, BCPSF_AUTOINC
    ldh [rOCPS], a
    ld hl, CgbObjPalette
    ld b, 8
.objPalette:
    ld a, [hl+]
    ldh [rOCPD], a
    dec b
    jr nz, .objPalette
    jr .palettesDone
.dmgPalettes:
    ld a, DMG_OBP
    ldh [rOBP0], a
.palettesDone:
    xor a
    call ApplyPalette ; step 0, plain white

    ; sound on, both channels on both speakers
    ld a, $80
    ldh [rNR52], a
    ld a, $77
    ldh [rNR50], a
    ld a, $FF
    ldh [rNR51], a

    xor a
    ldh [rSCY], a
    ldh [rSCX], a
    ldh [hFrame], a
    ldh [hOAMEnd], a
    ldh [hButtons], a
    ld a, WIN_Y
    ldh [rWY], a
    ld a, 7
    ldh [rWX], a
    ld a, $FF
    ldh [hPalReq], a
    call ResetScene

    ld a, LCDC_DEFAULT
    ldh [rLCDC], a
    ld a, IEF_VBLANK
    ldh [rIE], a
    xor a
    ldh [rIF], a
    ei

MainLoop:
    halt

    ; VBlank: push the frame prepared during the previous loop
    ld a, HIGH(wShadowOAM)
    call hDMA
    ldh a, [hSCY]
    ldh [rSCY], a
    ldh a, [hWX]
    ldh [rWX], a
    ldh a, [hPalReq]
    cp $FF
    jr z, .noPalette
    call ApplyPalette
    ld a, $FF
    ldh [hPalReq], a
.noPalette:

    ; embedded mode hands control back once its last frame is shown
    ldh a, [hIntroDone]
    and a
    ret nz

    ; logic for the next frame
    ld hl, hFrame
    inc [hl]
    call ReadButtons
    ldh [hPressed], a
    ldh a, [hIntroMode]
    and a
    jr z, .dispatch
    ldh a, [hPressed]
    and PADF_START | PADF_A
    jr z, .dispatch
    ; embedded skip: cut to white and leave on the next VBlank
    xor a
    ldh [hPalReq], a
    ldh [hSCY], a
    inc a
    ldh [hIntroDone], a
    ld hl, wShadowOAM
    call FinishOAM
    jr MainLoop
.dispatch:
    ldh a, [hState]
    add a
    add LOW(StateTable)
    ld l, a
    adc HIGH(StateTable)
    sub l
    ld h, a
    ld a, [hl+]
    ld h, [hl]
    ld l, a
    call CallHL
    jr MainLoop

CallHL:
    jp hl

StateTable:
    dw StateFadeIn
    dw StateFly
    dw StateZoom
    dw StateReveal
    dw StateWrite
    dw StateFadeOut

; -----------------------------------------------------------------------------
; States
; -----------------------------------------------------------------------------

StateFadeIn:
    ld hl, hTimer
    ld a, [hl]
    inc [hl]
    cp 16
    jr z, .done
    rrca
    ret c ; one palette step every other frame
    ldh [hPalReq], a
    ret
.done:
    ld a, STATE_FLY
    ldh [hState], a
    ld de, PathFly
    jp StorePtr

StateFly:
    call LoadPtr
    call DrawBee
    call StorePtr
    ld a, e
    cp LOW(PathFlyEnd)
    ret nz
    ld a, d
    cp HIGH(PathFlyEnd)
    ret nz
    ld a, STATE_ZOOM
    ldh [hState], a
    ld de, ZoomTable
    jp StorePtr

StateZoom:
    call LoadPtr
    ld hl, wShadowOAM
    REPT 4
        call DrawRect
    ENDR
    call FinishOAM
    call StorePtr
    ld a, e
    cp LOW(ZoomTableEnd)
    ret nz
    ld a, d
    cp HIGH(ZoomTableEnd)
    ret nz
    ld a, STATE_REVEAL
    ldh [hState], a
    ret

; swaps the zoom sprites for the background logo, both land on the same
; VBlank so the switch is invisible
StateReveal:
    ld a, PAL_REVEAL
    ldh [hPalReq], a
    xor a
    ldh [hTimer], a
    call PlayNote1
    ld a, STATE_WRITE
    ldh [hState], a
    ld de, PathWrite
    call StorePtr
    ; fall through, the first bee frame sits behind the logo

StateWrite:
    ; snap effects: a short screen thud and the second chime note
    ld hl, hTimer
    ld a, [hl]
    cp 8
    jr nc, .effectsDone
    inc [hl]
    cp 6
    call z, PlayNote2
    ldh a, [hTimer]
    dec a
    ld b, 0
    cp SHAKE_LEN
    jr nc, .setScroll
    add LOW(ShakeTable)
    ld l, a
    adc HIGH(ShakeTable)
    sub l
    ld h, a
    ld b, [hl]
.setScroll:
    ld a, b
    ldh [hSCY], a
.effectsDone:

    ldh a, [hPressed]
    and PADF_START | PADF_A
    jr nz, .fadeOut

    call LoadPtr
    call DrawBee
    ld a, e
    cp LOW(PathOrbitEnd)
    jr nz, .store
    ld a, d
    cp HIGH(PathOrbitEnd)
    jr nz, .store
    ld de, PathOrbitLoop
    ldh a, [hIntroMode]
    and a
    jr nz, .fadeOut ; embedded: one full orbit is enough
.store:
    jp StorePtr

.fadeOut:
    ld a, STATE_FADE_OUT
    ldh [hState], a
    xor a
    ldh [hTimer], a
    ld hl, wShadowOAM
    jp FinishOAM ; hides every object

StateFadeOut:
    ld hl, hTimer
    ld a, [hl]
    inc [hl]
    cp 16
    jr z, .done
    rrca
    ret c
    add PAL_REVEAL
    ldh [hPalReq], a
    ret
.done:
    ldh a, [hIntroMode]
    and a
    jr z, ResetScene
    ldh [hIntroDone], a
    ret

ResetScene:
    xor a
    ldh [hState], a ; STATE_FADE_IN
    ldh [hTimer], a
    ldh [hSCY], a
    ld a, 7 ; window covers the text again
    ldh [hWX], a
    ret

; -----------------------------------------------------------------------------
; Object builders, they write into the shadow OAM
; -----------------------------------------------------------------------------

; Draws the bee and its pollen trail for a path entry.
; in: de = path entry (OAM Y, OAM X, attributes, WX)
; out: de = next entry
DrawBee:
    ld hl, wShadowOAM
    ld a, [de]
    ld b, a ; Y
    inc e ; entries are 4 byte aligned, e never wraps inside one
    ld a, [de]
    ld c, a ; X
    inc e
    ld a, [de]
    ldh [hAttr], a
    inc e
    ld a, [de]
    ldh [hWX], a
    dec e
    dec e
    dec e
    push de

    ; wing flap phase picks the tile pair
    ldh a, [hFrame]
    rrca
    and 3
    add LOW(FlapTiles)
    ld e, a
    adc HIGH(FlapTiles)
    sub e
    ld d, a
    ld a, [de]
    ld d, a
    ; facing left swaps both columns and mirrors them
    ldh a, [hAttr]
    ld e, a
    and OAMF_XFLIP
    swap a ; $20 -> $02
    or d
    ld d, a

    ld a, b
    ld [hl+], a
    ld a, c
    ld [hl+], a
    ld a, d
    ld [hl+], a
    ld a, e
    ld [hl+], a
    ld a, b
    ld [hl+], a
    ld a, c
    add 8
    ld [hl+], a
    ld a, d
    xor 2
    ld [hl+], a
    ld a, e
    ld [hl+], a

    ; trail: older path entries, b = bee Y and c = bee X for the overlap test
    pop de
    push de
    ld a, DOT_BASE
    ldh [hDotTile], a
    ld a, TRAIL_DOTS
    ldh [hCount], a
.dot:
    ld a, e
    sub TRAIL_STEP * 4
    ld e, a
    jr nc, .noBorrow
    dec d
.noBorrow:
    ld a, [de]
    and a
    jr z, .nextDot ; padding entry
    ; skip dots over the bee, DMG would draw them on top of it
    sub b
    add 10
    cp 20
    jr nc, .drawDot
    inc e
    ld a, [de]
    dec e
    sub c
    add 10
    cp 20
    jr c, .nextDot
.drawDot:
    ld a, [de]
    ld [hl+], a
    inc e
    ld a, [de]
    add 4
    ld [hl+], a
    ldh a, [hDotTile]
    ld [hl+], a
    inc e
    ld a, [de]
    and OAMF_PRI
    ld [hl+], a
    dec e
    dec e
.nextDot:
    ldh a, [hDotTile]
    add 2
    ldh [hDotTile], a
    ldh a, [hCount]
    dec a
    ldh [hCount], a
    jr nz, .dot

    pop de
    inc de
    inc de
    inc de
    inc de
    jp FinishOAM

; Draws a solid square with 8x16 objects. The last column overlaps the one
; before it and the last row uses a partial height tile. With the Y flip
; flag the rows go upwards (flipped tiles), so the unused part of the
; partial row spills away from the other squares and no scanline ever
; gets more than 10 objects.
; in: de = rect (OAM Y, OAM X, size, tile base, flags), hl = next OAM slot
; out: de = next rect, hl = next OAM slot
DrawRect:
    ld a, [de]
    inc de
    ldh [hRectY], a
    ld a, [de]
    inc de
    ldh [hRectX], a
    ld a, [de]
    inc de
    ldh [hRectSize], a
    ldh [hRectRemH], a
    ld a, [de]
    inc de
    ldh [hRectBase], a
    ld a, [de]
    inc de
    ldh [hRectAttr], a
.row:
    ldh a, [hRectRemH]
    cp 17
    jr c, .heightOk
    ld a, 16
.heightOk:
    dec a
    add a
    ld b, a
    ldh a, [hRectBase]
    add b
    ld b, a ; tile = base + (height - 1) * 2
    ldh a, [hRectX]
    ld c, a
    ldh a, [hRectSize]
    ldh [hRectRemW], a
.col:
    ldh a, [hRectY]
    ld [hl+], a
    ld a, c
    ld [hl+], a
    ld a, b
    ld [hl+], a
    ldh a, [hRectAttr]
    ld [hl+], a
    ldh a, [hRectRemW]
    sub 8
    jr c, .rowDone
    jr z, .rowDone
    cp 8
    jr nc, .fullStep
    add c ; last column, overlaps the previous one
    ld c, a
    ld a, 8
    ldh [hRectRemW], a
    jr .col
.fullStep:
    ldh [hRectRemW], a
    ld a, c
    add 8
    ld c, a
    jr .col
.rowDone:
    ldh a, [hRectRemH]
    sub 16
    ret c
    ret z
    ldh [hRectRemH], a
    ldh a, [hRectAttr]
    and a
    ld b, 16
    jr z, .down
    ld b, -16
.down:
    ldh a, [hRectY]
    add b
    ldh [hRectY], a
    jr .row

; -----------------------------------------------------------------------------
; Helpers
; -----------------------------------------------------------------------------

LoadPtr:
    ldh a, [hPtr]
    ld e, a
    ldh a, [hPtr + 1]
    ld d, a
    ret

StorePtr:
    ld a, e
    ldh [hPtr], a
    ld a, d
    ldh [hPtr + 1], a
    ret

; in: a = palette step (0 white, 1..7 fade in, 8 revealed, 9..15 fade out)
ApplyPalette:
    ld c, a
    ldh a, [hIsCGB]
    and a
    jr nz, .cgb
    ld b, 0
    ld hl, DmgPalettes
    add hl, bc
    ld a, [hl]
    ldh [rBGP], a
    ret
.cgb:
    ld a, c
    swap a
    ld l, a
    ld h, 0
    add hl, hl
    add hl, hl ; step * 64
    ld de, CgbPalettes
    add hl, de
    ld a, BCPSF_AUTOINC
    ldh [rBCPS], a
    ld c, LOW(rBCPD)
    ld b, 8
.loop:
    REPT 8
        ld a, [hl+]
        ldh [c], a
    ENDR
    dec b
    jr nz, .loop
    ret

; out: a = action buttons pressed since the last call (bit 0 A, bit 3 Start)
ReadButtons:
    ld a, P1F_GET_BTN
    ldh [rP1], a
    ldh a, [rP1]
    ldh a, [rP1]
    ldh a, [rP1]
    cpl
    and $0F
    ld b, a
    ld a, P1F_GET_NONE
    ldh [rP1], a
    ldh a, [hButtons]
    cpl
    and b
    ld c, a
    ld a, b
    ldh [hButtons], a
    ld a, c
    ret

PlayNote1:
    xor a
    ldh [rNR10], a
    ld a, $80 ; 50% duty
    ldh [rNR11], a
    ld a, $F3 ; full volume, fading out
    ldh [rNR12], a
    ld a, LOW(NOTE_C6)
    ldh [rNR13], a
    ld a, $80 | HIGH(NOTE_C6)
    ldh [rNR14], a
    ret

PlayNote2:
    ld a, $80
    ldh [rNR21], a
    ld a, $C4
    ldh [rNR22], a
    ld a, LOW(NOTE_G6)
    ldh [rNR23], a
    ld a, $80 | HIGH(NOTE_G6)
    ldh [rNR24], a
    ret

SECTION "Intro variables", HRAM
hIntroMode: ds 1
hIntroDone: ds 1
hState: ds 1
hTimer: ds 1
hFrame: ds 1
hPtr: ds 2
hPalReq: ds 1
hSCY: ds 1
hWX: ds 1
hAttr: ds 1
hDotTile: ds 1
hCount: ds 1
hButtons: ds 1
hPressed: ds 1
hRectY: ds 1
hRectX: ds 1
hRectSize: ds 1
hRectRemH: ds 1
hRectRemW: ds 1
hRectBase: ds 1
hRectAttr: ds 1
